const catalogs = Object.freeze(Object.fromEntries(
  SUPPORTED_LOCALES.map(({ code }) => [
    code,
    Object.freeze({
      ...legacyCatalogs.en,
      ...(legacyCatalogs[code] || {}),
      ...chatEnhancementCatalogs[code],
    }),
  ]),
));

function interpolate(message, values = {}) {
  return String(message).replace(/\{([\w.-]+)\}/g, (match, key) => (
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match
  ));
}

export function translate(key, values = {}, locale = getLocale()) {
  const normalized = normalizeLocale(locale) || DEFAULT_LOCALE;
  const message = catalogs[normalized]?.[key] ?? catalogs[DEFAULT_LOCALE]?.[key] ?? key;
  return interpolate(message, values);
}

export const t = translate;

export function formatDate(value, options = {}, locale = getLocale()) {
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) return '';
  return new Intl.DateTimeFormat(locale, options).format(date);
}

export function formatTime(value, options = {}, locale = getLocale()) {
  return formatDate(value, { hour: '2-digit', minute: '2-digit', ...options }, locale);
}

export function normalizeSearchText(value, locale = getLocale()) {
  return String(value || '')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLocaleLowerCase(locale);
}

export function hasTranslation(key, locale = getLocale()) {
  const normalized = normalizeLocale(locale) || DEFAULT_LOCALE;
  return Object.prototype.hasOwnProperty.call(catalogs[normalized] || {}, key);
}

export function getCatalog(locale = getLocale()) {
  const normalized = normalizeLocale(locale) || DEFAULT_LOCALE;
  return catalogs[normalized] || catalogs[DEFAULT_LOCALE];
}
